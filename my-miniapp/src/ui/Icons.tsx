/**
 * Icons.tsx: the small line drawings used on the Tinker screen.
 *
 * WHY THIS FILE EXISTS
 *   The screen needs a dozen icons and no icon library is installed. Each icon
 *   is one inline SVG, so nothing is downloaded and the bundle stays small.
 *
 * HOW THEY BEHAVE
 *   Every icon takes the same three props (`size`, `className`, `style`) and
 *   draws with `currentColor`, so it follows the colour of the text around it.
 *   That is why the icons need no change between light and dark mode.
 *   They are decoration: `aria-hidden` keeps screen readers on the button text.
 *
 * The first twelve icons are the teammate's originals. The last four
 * (camera, key, bin, warning) were added for the new buttons.
 */

